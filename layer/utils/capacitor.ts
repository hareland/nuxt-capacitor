import type { CapacitorConfig } from '@capacitor/cli'
import { join } from 'node:path'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const name = 'nuxt-capacitor'

export type CapacitorConfigOutput = 'json' | 'ts' | 'js' | 'mjs'

const outputFiles: Record<CapacitorConfigOutput, string> = {
  json: 'capacitor.config.json',
  ts: 'capacitor.config.ts',
  js: 'capacitor.config.js',
  mjs: 'capacitor.config.mjs',
}

export const capacitorConfigFiles = Object.values(outputFiles)

export const resolveConfigFileName = (output: CapacitorConfigOutput): string => {
  const file = outputFiles[output]
  if (!file) {
    throw new Error(`[${name}] Unknown capacitor "output" "${output}". Use one of: ${Object.keys(outputFiles).join(', ')}.`)
  }
  return file
}

/** Config files in the project root that Capacitor could pick up instead of the generated one. */
export const findConflictingConfigFiles = (rootDir: string, output: CapacitorConfigOutput): string[] => {
  const target = resolveConfigFileName(output)
  return capacitorConfigFiles.filter(file => file !== target && existsSync(join(rootDir, file)))
}

const header = `Auto generated by ${name} from nuxt.config.ts > capacitor.config. Do not edit.`

export const renderCapacitorConfig = (output: CapacitorConfigOutput, config: CapacitorConfig): string => {
  const body = JSON.stringify(config, null, 2)
  switch (output) {
    case 'json':
      return `${body}\n`
    case 'ts':
      return [
        `// ${header}`,
        `import type { CapacitorConfig } from '@capacitor/cli'`,
        ``,
        `const config: CapacitorConfig = ${body}`,
        ``,
        `export default config`,
        ``,
      ].join('\n')
    case 'js':
    case 'mjs':
      return [
        `// ${header}`,
        `/** @type {import('@capacitor/cli').CapacitorConfig} */`,
        `const config = ${body}`,
        ``,
        `export default config`,
        ``,
      ].join('\n')
  }
}

/** Writes the config file, skipping the write when nothing changed. Returns the file path. */
export const writeCapacitorConfig = (rootDir: string, output: CapacitorConfigOutput, config: CapacitorConfig): string => {
  const file = join(rootDir, resolveConfigFileName(output))
  const contents = renderCapacitorConfig(output, config)
  if (!existsSync(file) || readFileSync(file, 'utf-8') !== contents) {
    writeFileSync(file, contents, 'utf-8')
  }
  return file
}
